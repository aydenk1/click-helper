"""Record and build a standalone click-helper.exe on Windows."""

import argparse
import json
import os
from pathlib import Path
import shutil
import subprocess
import tempfile

from record import positive_size, seconds


ROOT = Path(__file__).resolve().parents[1]
GENERATED = ROOT / "generated" / "windows"
BUILD = ROOT / "build" / "windows"
HEADER = GENERATED / "config.h"
DEFAULT_CC = "x86_64-w64-mingw32-clang.exe"


def compile_exe(compiler, name, *, recorder=False):
    BUILD.mkdir(parents=True, exist_ok=True)
    output = BUILD / name
    # Replace an existing executable only after the compiler and linker succeed.
    with tempfile.TemporaryDirectory(prefix="link-", dir=BUILD) as temporary:
        staged = Path(temporary) / name
        mode = ["-DCLICK_HELPER_RECORD"] if recorder else ["-I", str(GENERATED)]
        subprocess.run([
            compiler, "-std=c11", "-O2", "-Wall", "-Wextra", "-Wpedantic", "-Werror",
            "-municode", "-static", *mode, str(ROOT / "src" / "helper_windows.c"),
            "-luser32", "-ldwmapi", "-o", str(staged),
        ], check=True)
        staged.replace(output)
    return output


def wide_array(name, value):
    encoded = value.encode("utf-16-le", errors="surrogatepass")
    units = [f"0x{int.from_bytes(encoded[i:i + 2], 'little'):04x}"
             for i in range(0, len(encoded), 2)]
    units.append("0")
    yield f"static const wchar_t {name}[] = {{"
    for i in range(0, len(units), 12):
        yield "    " + ", ".join(units[i:i + 12]) + ","
    yield "};"


def write_header(executable, command, args, recording):
    lines = [
        "/* Generated by tools/windows.py. Private build input. */",
        "#ifndef CLICK_HELPER_WINDOWS_CONFIG_H",
        "#define CLICK_HELPER_WINDOWS_CONFIG_H",
        *wide_array("APP_PATH", executable),
        *wide_array("APP_COMMAND", command),
        *wide_array("APP_CLASS", recording["class"]),
        f"#define WINDOW_WIDTH {args.width}",
        f"#define WINDOW_HEIGHT {args.height}",
        f"#define WINDOW_DPI {recording['dpi']}",
        f"#define POSITION_ABSOLUTE {int(args.position == 'absolute')}",
        f"#define STARTUP_DELAY_MS {round(args.startup_delay * 1000)}",
        f"#define CLICK_DELAY_MS {round(args.click_delay * 1000)}",
        f"#define LAUNCH_TIMEOUT_MS {round(args.timeout * 1000)}",
        "static const Point CLICKS[] = {",
        *(f"    {{{x}, {y}}}," for x, y in recording["points"]),
        "};",
        "#endif",
        "",
    ]
    GENERATED.mkdir(parents=True, exist_ok=True)
    with tempfile.TemporaryDirectory(prefix="record-", dir=GENERATED) as temporary:
        staged = Path(temporary) / "config.h"
        staged.write_text("\n".join(lines), encoding="ascii", newline="\n")
        staged.replace(HEADER)


def record(compiler, args):
    argv = args.program
    if argv[:1] == ["--"]:
        argv = argv[1:]
    if not argv:
        raise ValueError("specify a Windows executable after --")
    startup_ms = round(args.startup_delay * 1000)
    timeout_ms = round(args.timeout * 1000)
    if timeout_ms <= startup_ms:
        raise ValueError("--timeout must be longer than --startup-delay")
    executable = Path(shutil.which(argv[0]) or argv[0]).resolve(strict=True)
    if executable.suffix.lower() != ".exe" or not executable.is_file():
        raise ValueError("the target must be a Windows .exe file")
    command = subprocess.list2cmdline([str(executable), *argv[1:]])
    recorder = compile_exe(compiler, "click-helper-record.exe", recorder=True)
    result = subprocess.run([
        str(recorder), str(executable), command, args.match_class, str(args.width),
        str(args.height), str(startup_ms), str(timeout_ms),
        str(int(args.position == "absolute")),
    ], stdout=subprocess.PIPE, check=True)
    write_header(str(executable), command, args, json.loads(result.stdout))
    print(f"Saved {HEADER}. Run the build command to compile playback.")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--cc", default=DEFAULT_CC, help="path to the x64 LLVM-MinGW compiler")
    commands = parser.add_subparsers(dest="action", required=True)
    capture = commands.add_parser("record", help="launch an app and record left-clicks")
    capture.add_argument("--width", type=positive_size, default=800)
    capture.add_argument("--height", type=positive_size, default=600)
    capture.add_argument("--position", choices=("relative", "absolute"), default="relative")
    capture.add_argument("--match-class", default="")
    capture.add_argument("--startup-delay", type=seconds, default=1.0)
    capture.add_argument("--click-delay", type=seconds, default=0.25)
    capture.add_argument("--timeout", type=seconds, default=20.0)
    capture.add_argument("program", nargs=argparse.REMAINDER)
    commands.add_parser("build", help="compile the saved recording into click-helper.exe")
    args = parser.parse_args()
    try:
        if os.name != "nt":
            raise ValueError("run the Windows recorder and builder on Windows")
        if args.action == "build" and not HEADER.is_file():
            raise ValueError("run the record command before building playback")
        compiler = shutil.which(args.cc)
        if compiler is None:
            raise ValueError("put the x64 LLVM-MinGW compiler on PATH or supply --cc")
        if args.action == "record":
            record(compiler, args)
        else:
            print(f"Built {compile_exe(compiler, 'click-helper.exe')}")
    except KeyboardInterrupt:
        parser.exit(130, "click-helper: cancelled\n")
    except subprocess.CalledProcessError as error:
        parser.exit(1, f"click-helper: recorder or compiler exited with status {error.returncode}\n")
    except (OSError, ValueError) as error:
        parser.exit(1, f"click-helper: {error}\n")


if __name__ == "__main__":
    main()
